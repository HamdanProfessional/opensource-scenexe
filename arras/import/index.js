const fs = require('fs')
const path = require('path')
const { SOURCES, DEFAULT_SOURCE, loadOrderFor, cacheDirFor, fetchAll } = require('./fetch.js')
const { loadOsa } = require('./sandbox.js')
const { makeConverter } = require('./convert.js')

const ROOT = path.join(__dirname, '..', '..')
const TANK_DATA = path.join(ROOT, 'tankData')
const LICENSE_OUT = path.join(ROOT, 'arras', 'LICENSE-open-source-arras.txt')

const parseArgs = function(argv) {
  const args = { source: DEFAULT_SOURCE, sha: '', offline: false }
  for(let i = 0; i < argv.length; i++) {
    if(argv[i] === '--sha') { args.sha = argv[++i] }
    else if(argv[i] === '--source') { args.source = argv[++i] }
    else if(argv[i] === '--offline') { args.offline = true }
  }
  if(!SOURCES[args.source]) { throw new Error('unknown source ' + args.source + ', use one of: ' + Object.keys(SOURCES).join(', ')) }
  if(!args.sha) { args.sha = SOURCES[args.source].sha }
  return args
}

const writeEntries = function(file, target, entries) {
  let text = '_(' + target + ', {\n'
  for(const key of Object.keys(entries)) {
    text += '  ' + JSON.stringify(key).replace(/^"|"$/g, "'") + ': ' + JSON.stringify(entries[key]) + ',\n'
  }
  text += '})\n'
  fs.writeFileSync(file, text)
  return text.length
}

const run = async function() {
  const args = parseArgs(process.argv.slice(2))
  const cacheDir = args.offline ? cacheDirFor(args.sha) : await fetchAll(args.source, args.sha)
  const osa = loadOsa(cacheDir, loadOrderFor(args.source))
  const report = {}
  const converter = makeConverter(osa.classTable, report)

  const reachable = converter.reachableFrom('basic')
  const weapons = {}
  const bodies = {}
  const labels = new Map()
  let barrelCount = 0
  for(const name of reachable) {
    const out = converter.convertTank(name)
    if(!out) { continue }
    weapons[out.key] = out.weapon
    bodies[out.key] = out.body
    barrelCount += out.weapon.barrels.length
    if(labels.has(out.weapon.label)) {
      console.log('duplicate label ' + out.weapon.label + ': ' + labels.get(out.weapon.label) + ' and ' + name)
    }
    labels.set(out.weapon.label, name)
  }
  const upgrades = converter.buildUpgradeMap(Object.keys(weapons).map(function(k) { return k.slice('arras:'.length) }))

  const sizes = [
    writeEntries(path.join(TANK_DATA, 'weapons', '9-arras.js'), 'weapons', weapons),
    writeEntries(path.join(TANK_DATA, 'bodies', '9-arras.js'), 'bodies', bodies),
    writeEntries(path.join(TANK_DATA, 'upgrades', 'arras.js'), 'weaponUpgradeMap', upgrades)
  ]

  const licensePath = path.join(cacheDir, 'LICENSE')
  const header = 'Source: github.com/' + SOURCES[args.source].repo + ' at commit ' + args.sha + '\n\n'
  fs.writeFileSync(LICENSE_OUT, header + fs.readFileSync(licensePath, 'utf8'))

  console.log('source: ' + args.source + ' sha: ' + args.sha)
  console.log('loader failures: ' + JSON.stringify(osa.failures))
  console.log('reachable: ' + reachable.length + ', converted: ' + Object.keys(weapons).length + ', barrels: ' + barrelCount)
  console.log('upgrade entries: ' + Object.keys(upgrades).length)
  console.log('generated bytes (weapons, bodies, upgrades): ' + sizes.join(', ') + ' total ' + sizes.reduce(function(a, b) { return a + b }, 0))
  for(const bucket of Object.keys(report)) {
    console.log(bucket + ': ' + JSON.stringify(report[bucket]))
  }
}

run().catch(function(err) {
  console.error(err)
  process.exit(1)
})
